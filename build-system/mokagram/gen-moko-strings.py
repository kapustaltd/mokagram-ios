#!/usr/bin/env python3
"""Generates MokoStringsTable.generated.swift from the Desktop and iOS string tables.

Usage: python3 build-system/mokagram/gen-moko-strings.py
Inputs: submodules/Moko/MokoCore/Strings/{desktop,ios}.inc, lines of `{ "Русский", "English" },`.
desktop.inc is a verbatim copy of Desktop's Telegram/SourceFiles/mokagram/lang/mokagram_lang_table.inc.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STRINGS = ROOT / 'submodules/Moko/MokoCore/Strings'
OUTPUT = ROOT / 'submodules/Moko/MokoCore/Sources/MokoStringsTable.generated.swift'
PAIR = re.compile(r'\{\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}')


HEX_RUN = re.compile(r'(?:\\x[0-9A-Fa-f]{2})+')


def swift_literal(text):
    # C \xHH byte runs (UTF-8) become the characters they encode; other escapes are shared with Swift.
    return HEX_RUN.sub(lambda m: bytes.fromhex(m.group(0).replace('\\x', '')).decode('utf-8'), text)


def read(name):
    text = (STRINGS / name).read_text(encoding='utf-8')
    return {swift_literal(m.group(1)): swift_literal(m.group(2)) for m in PAIR.finditer(text)}


def main():
    table = read('desktop.inc')
    table.update(read('ios.inc'))
    lines = [
        '// Generated by build-system/mokagram/gen-moko-strings.py from Strings/desktop.inc and Strings/ios.inc.',
        '// Do not edit; edit the .inc files and run the script again.',
        '',
        'let mokoEnglishTable: [String: String] = [',
    ]
    lines += [f'    "{key}": "{table[key]}",' for key in sorted(table)]
    lines += [']', '']
    OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{len(table)} strings -> {OUTPUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
